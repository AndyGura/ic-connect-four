"""Writes src/Book.mo from the generator's output files (lines "moves col value").

    python3 tools/book/make_book.py tools/book/*.txt

Each entry is one Nat64: (key << 4) | (win << 3) | col, where key is the
position's cur + mask (the discs of the seat on turn plus every disc, as in
Search.mo), the smaller of the position's and its mirror image's, and col is
mirrored with it. Sorted, for a binary search.
"""
import os, sys

def position(moves):
    cur = mask = 0
    for ch in moves:
        c = int(ch)
        mv = (mask + (1 << 7 * c)) & (0x3F << 7 * c)
        cur ^= mask
        mask |= mv
    return cur, mask

def mirror(x):
    return sum(((x >> (7 * c)) & 0x7F) << (7 * (6 - c)) for c in range(7))

entries = {}
twins = 0
for path in sys.argv[1:]:
    for line in open(path):
        parts = line.split()
        if len(parts) == 2:  # the empty position: "<col> <value>"
            parts = [""] + parts
        moves, col, value = parts[0], int(parts[1]), int(parts[2])
        cur, mask = position(moves)
        key, mkey = cur + mask, mirror(cur) + mirror(mask)
        if mkey < key:
            key, col = mkey, 6 - col
        e = (key << 4) | ((1 if value == 1 else 0) << 3) | col
        if key in entries:
            # A position and its mirror image, reached from different
            # subtrees, may each have kept a different move that keeps the
            # value; either is right, and so is a draw kept over a draw.
            if (entries[key] >> 3) & 1 != (e >> 3) & 1:
                sys.exit(f"entries for {moves} disagree on the value")
            twins += entries[key] != e
            continue
        entries[key] = e

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "Book.mo")
rows = sorted(entries.values())
with open(out, "w") as f:
    f.write("""import Nat64 "mo:core/Nat64";

/// Hard's opening book: a move that keeps the game-theoretic value for
/// every position the book's side can reach while following it (as Red
/// through its first moves; as Yellow wherever Red's opening let Yellow
/// win or draw), computed offline by an exact solver
/// (tools/book/). Generated by tools/book/make_book.py: do not edit.
module {

  /// Sorted; each is (key << 4) | (win << 3) | col, key = cur + mask of
  /// the position or of its mirror image, whichever is smaller.
  let ENTRIES : [Nat64] = [
""")
    for i in range(0, len(rows), 4):
        f.write("    " + " ".join(f"0x{r:x}," for r in rows[i:i + 4]) + "\n")
    f.write("""  ];

  public func size() : Nat = ENTRIES.size();

  func mirror(x : Nat64) : Nat64 {
    var r : Nat64 = 0;
    var c : Nat64 = 0;
    while (c < 7) {
      r |= ((x >> (7 * c)) & 0x7f) << (7 * (6 - c));
      c += 1;
    };
    r;
  };

  /// The book's move for the seat on turn (`cur`, `mask` as in Search.mo)
  /// and whether it wins (`true`) or draws (`false`) with perfect play.
  public func lookup(cur : Nat64, mask : Nat64) : ?(Nat, Bool) {
    let key = cur + mask;
    let mkey = mirror(cur) + mirror(mask);
    let flip = mkey < key;
    let k = if flip mkey else key;
    var lo = 0;
    var hi = ENTRIES.size();
    while (lo < hi) {
      let mid = (lo + hi) / 2;
      let e = ENTRIES[mid];
      let ek = e >> 4;
      if (ek == k) {
        let col = (e & 7).toNat();
        return ?(if flip 6 - col else col, e & 8 != 0);
      };
      if (ek < k) lo := mid + 1 else hi := mid;
    };
    null;
  };

};
""")
print(f"{len(rows)} entries ({twins} mirror twins kept once) -> {out}")
